data class UiYearMonth(val year: Int, val monthNumber: Int) {
    fun lengthOfMonth(): Int = when (monthNumber) {
        2 -> if (year % 4 == 0 && (year % 100 != 0 || year % 400 == 0)) 29 else 28
        4, 6, 9, 11 -> 30
        else -> 31
    }
        
    @Suppress("DEPRECATION")
    fun atDay(day: Int): LocalDate = LocalDate(year, monthNumber, day)

    companion object {
        fun now(): UiYearMonth {
            val date = Clock.System.now().toLocalDateTime(TimeZone.currentSystemDefault()).date
            return UiYearMonth(date.year, date.month.number)
        }
    }
}

private fun monthForPage(page: Int, initialPage: Int, baseMonth: UiYearMonth): UiYearMonth {
    val offset = page - initialPage
    var newYear = baseMonth.year + offset / 12
    var newMonth = baseMonth.monthNumber + offset % 12
    
    if (newMonth > 12) {
        newYear += newMonth / 12
        newMonth %= 12
    } else if (newMonth < 1) {
        newYear += (newMonth - 12) / 12
        newMonth = 12 + (newMonth % 12)
        if (newMonth == 12) {
            newYear -= 1
        }
    }
    return UiYearMonth(newYear, newMonth)
}

@Composable
fun CalendarHeader(
    currentMonth: UiYearMonth,
    onPrevMonth: () -> Unit,
    onNextMonth: () -> Unit
) {
    val monthName = when (currentMonth.monthNumber) {
        1 -> "January"
        2 -> "February"
        3 -> "March"
        4 -> "April"
        5 -> "May"
        6 -> "June"
        7 -> "July"
        8 -> "August"
        9 -> "September"
        10 -> "October"
        11 -> "November"
        12 -> "December"
        else -> ""
    }

    Row(
        modifier = Modifier.fillMaxWidth().padding(16.dp),
        horizontalArrangement = Arrangement.SpaceBetween,
        verticalAlignment = Alignment.CenterVertically
    ) {
        IconButton(onClick = onPrevMonth) {
            Icon(Icons.AutoMirrored.Filled.ArrowBack, contentDescription = "Previous Month")
        }

        Text(
            text = "$monthName ${currentMonth.year}",
            style = MaterialTheme.typography.titleLarge.copy(fontWeight = FontWeight.Bold)
        )

        IconButton(onClick = onNextMonth) {
            Icon(Icons.AutoMirrored.Filled.ArrowForward, contentDescription = "Next Month")
        }
    }
}

@Composable
fun CalendarGrid(
    currentMonth: UiYearMonth,
    loggedDates: Set<LocalDate>,    // Dates pulled from your DB history (bleeding dates)
    predictedDates: Set<LocalDate>, // Dates generated by the Rust Core
    fertileDates: Set<LocalDate>,    // Dates generated by the Rust Core
    sexualActivityDates: Map<LocalDate, String> = emptyMap(),
    symptomOnlyDates: Set<LocalDate> = emptySet(),
    zeroFlowDates: Set<LocalDate> = symptomOnlyDates,
    selectedDate: LocalDate?,
    onDateSelected: (LocalDate) -> Unit
) {
    val daysToRender = remember(currentMonth) {
        val firstDay = currentMonth.atDay(1)
        val startOffset = firstDay.dayOfWeek.isoDayNumber % 7 
        val lengthOfMonth = currentMonth.lengthOfMonth()
        
        val emptySlots = List(startOffset) { null }
        val actualDays = (1..lengthOfMonth).toList()
        
        emptySlots + actualDays
    }

    val today = remember { Clock.System.now().toLocalDateTime(TimeZone.currentSystemDefault()).date }
    val rows = remember(daysToRender) { daysToRender.chunked(7) }

    // Bounding the grid with exact rows and columns prevents cropping on all screen sizes
    Column(
        modifier = Modifier.fillMaxWidth().padding(horizontal = 16.dp)
    ) {
        rows.forEach { rowDays ->
            Row(modifier = Modifier.fillMaxWidth()) {
                rowDays.forEach { day ->
                    Box(
                        modifier = Modifier
                            .weight(1f)
                            .height(44.dp)
                            .padding(2.dp),
                        contentAlignment = Alignment.Center
                    ) {
                        if (day != null) {
                            val currentDate = currentMonth.atDay(day)
                            
                            val isLogged = loggedDates.contains(currentDate)
                            val isPredicted = predictedDates.contains(currentDate)
                            val isFertile = fertileDates.contains(currentDate)
                            val isToday = currentDate == today
                            val isSexual = sexualActivityDates.containsKey(currentDate)
                            val sexualType = sexualActivityDates[currentDate]?.lowercase()
                            val effectiveZeroFlow = if (zeroFlowDates.isNotEmpty()) zeroFlowDates else symptomOnlyDates
                            val isZeroFlow = effectiveZeroFlow.contains(currentDate) && !isLogged
                            
                            val appColors = LocalAppColors.current
                            val PeriodColor = appColors.primaryVariant
                            val FertileColor = appColors.secondaryVariant
                            val TodayColor = appColors.todayHighlight

                            Box(
                                modifier = Modifier
                                    .size(44.dp)
                                    .semantics(mergeDescendants = true) {
                                        contentDescription = buildString {
                                            append(currentDate.toHumanReadable())
                                            if (isToday) append(", Today")
                                            if (isLogged) append(", Period logged")
                                            if (isPredicted) append(", Predicted period")
                                            if (isFertile) append(", Fertile window")
                                            if (isZeroFlow) append(", Symptoms logged")
                                            if (isSexual) append(", Intimacy logged")
                                        }
                                    }
                                    .clickable { onDateSelected(currentDate) }
                                    .then(
                                        if (selectedDate == currentDate) {
                                            Modifier.border(2.dp, Color.Black, CircleShape)
                                        } else Modifier
                                    )
                                    .then(
                                        when {
                                            isLogged -> Modifier.background(PeriodColor, CircleShape)
                                            isFertile -> Modifier.background(FertileColor, CircleShape)
                                            isPredicted -> Modifier.drawBehind {
                                                drawCircle(
                                                    color = PeriodColor,
                                                    style = Stroke(
                                                        width = 1.5.dp.toPx(),
                                                        pathEffect = PathEffect.dashPathEffect(
                                                            intervals = floatArrayOf(8f, 8f), 
                                                            phase = 0f
                                                        )
                                                    )
                                                )
                                            }
                                            isZeroFlow -> Modifier.border(1.dp, PeriodColor.copy(alpha = 0.4f), CircleShape)
                                            else -> Modifier
                                        }
                                    ),
                                contentAlignment = Alignment.Center
                            ) {
                                Text(
                                    text = day.toString(),
                                    color = if (isLogged) Color.White else if (isToday) TodayColor else MaterialTheme.colorScheme.onSurface,
                                    style = MaterialTheme.typography.bodyMedium.copy(fontWeight = if (isToday || isLogged) FontWeight.Bold else FontWeight.Normal)
                                )
                                
                                Row(
                                    modifier = Modifier.align(Alignment.BottomCenter).padding(bottom = 2.dp),
                                    horizontalArrangement = Arrangement.spacedBy(2.dp),
                                    verticalAlignment = Alignment.CenterVertically
                                ) {
                                    if (isToday) {
                                        Box(modifier = Modifier.size(4.dp).clip(CircleShape).background(if (isLogged) Color.White else TodayColor))
                                    }
                                    if (isZeroFlow) {
                                        Box(modifier = Modifier.size(4.dp).clip(CircleShape).background(if (isLogged) Color.White else PeriodColor.copy(alpha = 0.6f)))
                                    }
                                    if (isSexual) {
                                        val icon = when (sexualType) {
                                            "protected" -> Icons.Default.CheckCircle
                                            "masturbation" -> Icons.Default.Person
                                            else -> Icons.Default.Favorite
                                        }
                                        val iconTint = when (sexualType) {
                                            "protected" -> Color(0xFF81C784)
                                            "masturbation" -> Color(0xFF64B5F6)
                                            else -> Color(0xFFE57373)
                                        }
                                        Icon(
                                            imageVector = icon, 
                                            contentDescription = null, 
                                            tint = if (isLogged) Color.White else iconTint, 
                                            modifier = Modifier.size(8.dp)
                                        )
                                    }
                                }
                            }
                        }
                    }
                }
                // Fill remaining empty slots in the last row to maintain alignment
                repeat(7 - rowDays.size) {
                    Spacer(modifier = Modifier.weight(1f).height(44.dp))
                }
            }
        }
    }
}

@Composable
fun CalendarScreen(
    cycleTracker: CycleTracker, 
    entries: List<CycleEntry>,
    isPartner: Boolean = false,
    partnerPerms: PartnerPermissions? = null,
    onEditEntry: (CycleEntry, String?) -> Unit,
    onDeleteEntry: (Long) -> Unit
) {
    val coroutineScope = rememberCoroutineScope()
    val initialPage = 500
    val pagerState = androidx.compose.foundation.pager.rememberPagerState(
        initialPage = initialPage,
        pageCount = { 1000 }
    )
    val baseMonth = remember { UiYearMonth.now() }

    val currentMonth = remember(pagerState.currentPage, baseMonth) {
        monthForPage(pagerState.currentPage, initialPage, baseMonth)
    }

    // CRITICAL: collectAsState() forces Compose to redraw the grid when the ViewModel pushes new arrays
    val loggedDates by cycleTracker.loggedDates.collectAsState()
    val predictedDates by cycleTracker.predictedDates.collectAsState()
    val fertileDates by cycleTracker.fertileDates.collectAsState()
    
    var selectedDate by remember { mutableStateOf<LocalDate?>(null) }

    Column(modifier = Modifier.fillMaxSize().background(MaterialTheme.colorScheme.background)) {
        CalendarHeader(
            currentMonth = currentMonth,
            onPrevMonth = {
                coroutineScope.launch {
                    pagerState.animateScrollToPage(pagerState.currentPage - 1)
                }
            },
            onNextMonth = {
                coroutineScope.launch {
                    pagerState.animateScrollToPage(pagerState.currentPage + 1)
                }
            }
        )
        
        // Weekdays Header
        Row(modifier = Modifier.fillMaxWidth().padding(horizontal = 8.dp)) {
            val weekDays = listOf("Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat")
            weekDays.forEach { day ->
                Text(
                    text = day,
                    modifier = Modifier.weight(1f),
                    textAlign = TextAlign.Center,
                    style = MaterialTheme.typography.bodySmall.copy(fontWeight = FontWeight.Bold),
                    color = Color.Gray
                )
            }
        }

        val zeroFlowDates = remember(entries, isPartner, partnerPerms) {
            if (isPartner && (partnerPerms?.shareSymptomsMoods != true)) {
                emptySet()
            } else {
                entries.filter {
                    val intVal = it.intensity ?: 0
                    intVal == 0 && (
                        it.intensity == 0 ||
                        !it.symptoms.isNullOrEmpty() ||
                        (it.painLevel ?: 0) > 0 ||
                        !it.notes.isNullOrEmpty()
                    )
                }.mapNotNull { runCatching { LocalDate.parse(it.date) }.getOrNull() }.toSet()
            }
        }

        val sexualActivityDates = remember(entries, isPartner, partnerPerms) {
            if (isPartner && (partnerPerms?.shareSexualActivity != true)) {
                emptyMap()
            } else {
                entries.mapNotNull { entry -> entry.sexualRelations?.let { LocalDate.parse(entry.date) to it } }.toMap()
            }
        }

        val periodGroups = remember(entries) { groupPeriodEntries(entries, includeZeroFlow = true) }
        val groups = remember(periodGroups, isPartner, partnerPerms) {
            if (isPartner) {
                if (partnerPerms?.shareCyclePhase != true) {
                    emptyList()
                } else {
                    periodGroups.filter { group ->
                        if (group.maxIntensity == 0) {
                            partnerPerms.shareSymptomsMoods
                        } else {
                            true
                        }
                    }
                }
            } else {
                periodGroups
            }
        }

        androidx.compose.foundation.pager.HorizontalPager(
            state = pagerState,
            modifier = Modifier.fillMaxWidth().wrapContentHeight()
        ) { page ->
            val pageMonth = remember(page, baseMonth) {
                monthForPage(page, initialPage, baseMonth)
            }

            val filteredLoggedDates = if (isPartner && (partnerPerms?.shareCyclePhase != true)) emptySet() else loggedDates
            val filteredPredictedDates = if (isPartner && (partnerPerms?.shareCyclePhase != true)) emptySet() else predictedDates
            val filteredFertileDates = if (isPartner && (partnerPerms?.shareCyclePhase != true)) emptySet() else fertileDates

            CalendarGrid(
                currentMonth = pageMonth,
                loggedDates = filteredLoggedDates,
                predictedDates = filteredPredictedDates,
                fertileDates = filteredFertileDates,
                sexualActivityDates = sexualActivityDates,
                symptomOnlyDates = zeroFlowDates,
                zeroFlowDates = zeroFlowDates,
                selectedDate = selectedDate,
                onDateSelected = { 
                    if (selectedDate == it) selectedDate = null else selectedDate = it 
                }
            )
        }

        // ADD THIS LINE RIGHT AFTER THE GRID
        CalendarLegend()
        
        Spacer(modifier = Modifier.height(16.dp))
        
        Row(
            modifier = Modifier.fillMaxWidth().padding(16.dp),
            horizontalArrangement = Arrangement.SpaceBetween,
            verticalAlignment = Alignment.CenterVertically
        ) {
            Text(
                text = selectedDate?.let { "Logs for ${it.toHumanReadable()}" } ?: "History",
                style = MaterialTheme.typography.titleMedium.copy(fontWeight = FontWeight.Bold)
            )
            if (selectedDate != null) {
                TextButton(onClick = { selectedDate = null }) {
                    Text("Clear Filter")
                }
            }
        }
        
        LazyColumn(
            modifier = Modifier.fillMaxWidth().weight(1f),
            contentPadding = PaddingValues(16.dp),
            verticalArrangement = Arrangement.spacedBy(12.dp)
        ) {
            if (selectedDate != null) {
                val displayEntries = entries.filter { it.date == selectedDate.toString() }
                items(displayEntries) { entry ->
                    HistoryItem(
                        entry = entry,
                        isPartner = isPartner,
                        partnerPerms = partnerPerms,
                        onEdit = { onEditEntry(entry, null) },
                        onDelete = { entry.id?.let { onDeleteEntry(it) } }
                    )
                }
                if (displayEntries.isEmpty()) {
                    item {
                        Text("No logs for this date.", color = Color.Gray, modifier = Modifier.padding(16.dp))
                    }
                }
                
                if (!isPartner) {
                    item {
                        val currentEntry = displayEntries.firstOrNull()
                        val periodEntry = displayEntries.firstOrNull { (it.intensity ?: 0) > 0 } ?: currentEntry

                        Button(
                            onClick = {
                                val entryToEdit = periodEntry ?: CycleEntry(
                                    id = 0L,
                                    date = selectedDate.toString(),
                                    intensity = 3,
                                    notes = "",
                                    sexualRelations = null,
                                    painLevel = 1,
                                    symptoms = ""
                                )
                                onEditEntry(entryToEdit, selectedDate.toString())
                            },
                            modifier = Modifier.fillMaxWidth().height(50.dp),
                            shape = RoundedCornerShape(12.dp),
                            colors = ButtonDefaults.buttonColors(containerColor = LocalAppColors.current.primary)
                        ) {
                            Icon(Icons.Default.Edit, contentDescription = null)
                            Spacer(Modifier.width(8.dp))
                            Text(
                                text = if (periodEntry != null) "Edit Period / Symptoms" else "Log Period / Symptoms",
                                style = MaterialTheme.typography.titleMedium
                            )
                        }
                    }

                    item {
                        val currentEntry = displayEntries.firstOrNull()
                        val currentRel = currentEntry?.sexualRelations

                        Column(modifier = Modifier.fillMaxWidth().padding(top = 16.dp)) {
                            Text("Log Sexual Activity", style = MaterialTheme.typography.titleMedium, fontWeight = FontWeight.Bold)
                            Spacer(Modifier.height(8.dp))
                            Row(
                                modifier = Modifier.fillMaxWidth(),
                                horizontalArrangement = Arrangement.SpaceEvenly
                            ) {
                                listOf("Protected", "Unprotected", "Masturbation").forEach { rel ->
                                    FilterChip(
                                        selected = currentRel == rel,
                                        onClick = { 
                                            val newRel = if (currentRel == rel) null else rel
                                            selectedDate?.let { cycleTracker.logSexualRelation(it, newRel) }
                                        },
                                        label = { Text(rel) }
                                    )
                                }
                            }
                        }
                    }
                } // End of if (!isPartner)
            } else {
                items(groups) { group ->
                    HistoryGroupItem(
                        group = group,
                        isPartner = isPartner,
                        partnerPerms = partnerPerms,
                        onEdit = {
                            val firstEntry = entries.firstOrNull { it.id in group.ids } ?: CycleEntry(
                                id = group.ids.firstOrNull() ?: 0L,
                                date = group.startDate.toString(),
                                intensity = group.maxIntensity,
                                notes = group.notes,
                                sexualRelations = null,
                                painLevel = group.maxPainLevel,
                                symptoms = group.symptoms.joinToString(", ")
                            )
                            onEditEntry(firstEntry, group.endDate.toString())
                        },
                        onDelete = {
                            group.ids.forEach { id -> onDeleteEntry(id) }
                        },
                        onEditDay = { dayEntry ->
                            onEditEntry(dayEntry, null)
                        }
                    )
                }
                if (groups.isEmpty()) {
                    item {
                        Text("No period logs found.", color = Color.Gray, modifier = Modifier.padding(16.dp))
                    }
                }
            }
        }
    }
}

data class PeriodGroup(
    val startDate: kotlinx.datetime.LocalDate,
    val endDate: kotlinx.datetime.LocalDate,
    val maxIntensity: Int,
    val notes: String,
    val ids: List<Long>,
    val maxPainLevel: Int? = null,
    val symptoms: Set<String> = emptySet(),
    val dailyEntries: List<CycleEntry> = emptyList()
)

fun groupPeriodEntries(entries: List<CycleEntry>, includeZeroFlow: Boolean = false): List<PeriodGroup> {
    val bleedingEntries = mutableListOf<Pair<LocalDate, CycleEntry>>()
    val zeroFlowEntries = mutableListOf<Pair<LocalDate, CycleEntry>>()

    for (entry in entries) {
        val date = runCatching { LocalDate.parse(entry.date) }.getOrNull() ?: continue
        val intensity = entry.intensity ?: 0
        if (intensity > 0) {
            bleedingEntries.add(Pair(date, entry))
        } else if (includeZeroFlow && (
            entry.intensity == 0 ||
            !entry.symptoms.isNullOrEmpty() ||
            (entry.painLevel ?: 0) > 0 ||
            !entry.notes.isNullOrEmpty() ||
            !entry.sexualRelations.isNullOrEmpty()
        )) {
            zeroFlowEntries.add(Pair(date, entry))
        }
    }

    bleedingEntries.sortBy { it.first }
    zeroFlowEntries.sortBy { it.first }

    val groups = mutableListOf<PeriodGroup>()

    if (bleedingEntries.isNotEmpty()) {
        var currentStart = bleedingEntries[0].first
        var currentEnd = bleedingEntries[0].first
        var maxInt = bleedingEntries[0].second.intensity ?: 0
        var combinedNotes = bleedingEntries[0].second.notes ?: ""
        var currentIds = mutableListOf<Long>()
        bleedingEntries[0].second.id?.let { currentIds.add(it) }
        var maxPain = bleedingEntries[0].second.painLevel
        var combinedSymptoms = bleedingEntries[0].second.symptoms?.split(",")?.map { it.trim() }?.filter { it.isNotEmpty() }?.toMutableSet() ?: mutableSetOf()
        var currentEntries = mutableListOf(bleedingEntries[0].second)

        for (i in 1 until bleedingEntries.size) {
            val (date, entry) = bleedingEntries[i]
            val prevDate = bleedingEntries[i-1].first

            if (date.toEpochDays() - prevDate.toEpochDays() <= 7L) {
                currentEnd = date
                val int = entry.intensity ?: 0
                if (int > maxInt) maxInt = int
                val pain = entry.painLevel
                if (pain != null && (maxPain == null || pain > maxPain)) maxPain = pain
                entry.symptoms?.split(",")?.map { it.trim() }?.filter { it.isNotEmpty() }?.let { combinedSymptoms.addAll(it) }
                if (!entry.notes.isNullOrBlank()) {
                    if (!combinedNotes.contains(entry.notes)) {
                        combinedNotes += if (combinedNotes.isBlank()) entry.notes else " | ${entry.notes}"
                    }
                }
                entry.id?.let { currentIds.add(it) }
                currentEntries.add(entry)
            } else {
                groups.add(PeriodGroup(currentStart, currentEnd, maxInt, combinedNotes, currentIds, maxPain, combinedSymptoms, currentEntries))
                currentStart = date
                currentEnd = date
                maxInt = entry.intensity ?: 0
                combinedNotes = entry.notes ?: ""
                currentIds = mutableListOf()
                entry.id?.let { currentIds.add(it) }
                maxPain = entry.painLevel
                combinedSymptoms = entry.symptoms?.split(",")?.map { it.trim() }?.filter { it.isNotEmpty() }?.toMutableSet() ?: mutableSetOf()
                currentEntries = mutableListOf(entry)
            }
        }
        groups.add(PeriodGroup(currentStart, currentEnd, maxInt, combinedNotes, currentIds, maxPain, combinedSymptoms, currentEntries))
    }

    if (includeZeroFlow && zeroFlowEntries.isNotEmpty()) {
        var currentStart = zeroFlowEntries[0].first
        var currentEnd = zeroFlowEntries[0].first
        var combinedNotes = zeroFlowEntries[0].second.notes ?: ""
        var currentIds = mutableListOf<Long>()
        zeroFlowEntries[0].second.id?.let { currentIds.add(it) }
        var maxPain = zeroFlowEntries[0].second.painLevel
        var combinedSymptoms = zeroFlowEntries[0].second.symptoms?.split(",")?.map { it.trim() }?.filter { it.isNotEmpty() }?.toMutableSet() ?: mutableSetOf()
        var currentEntries = mutableListOf(zeroFlowEntries[0].second)

        for (i in 1 until zeroFlowEntries.size) {
            val (date, entry) = zeroFlowEntries[i]
            val prevDate = zeroFlowEntries[i-1].first

            if (date.toEpochDays() - prevDate.toEpochDays() <= 1L) {
                currentEnd = date
                val pain = entry.painLevel
                if (pain != null && (maxPain == null || pain > maxPain)) maxPain = pain
                entry.symptoms?.split(",")?.map { it.trim() }?.filter { it.isNotEmpty() }?.let { combinedSymptoms.addAll(it) }
                if (!entry.notes.isNullOrBlank()) {
                    if (!combinedNotes.contains(entry.notes)) {
                        combinedNotes += if (combinedNotes.isBlank()) entry.notes else " | ${entry.notes}"
                    }
                }
                entry.id?.let { currentIds.add(it) }
                currentEntries.add(entry)
            } else {
                groups.add(PeriodGroup(currentStart, currentEnd, 0, combinedNotes, currentIds, maxPain, combinedSymptoms, currentEntries))
                currentStart = date
                currentEnd = date
                combinedNotes = entry.notes ?: ""
                currentIds = mutableListOf()
                entry.id?.let { currentIds.add(it) }
                maxPain = entry.painLevel
                combinedSymptoms = entry.symptoms?.split(",")?.map { it.trim() }?.filter { it.isNotEmpty() }?.toMutableSet() ?: mutableSetOf()
                currentEntries = mutableListOf(entry)
            }
        }
        groups.add(PeriodGroup(currentStart, currentEnd, 0, combinedNotes, currentIds, maxPain, combinedSymptoms, currentEntries))
    }

    return groups.sortedByDescending { it.startDate }
}

@Composable
fun HistoryGroupItem(
    group: PeriodGroup, 
    isPartner: Boolean = false, 
    partnerPerms: PartnerPermissions? = null, 
    onEdit: () -> Unit = {}, 
    onDelete: () -> Unit = {},
    onEditDay: (CycleEntry) -> Unit = {}
) {
    val periodColor = LocalAppColors.current.primary
    val showIntensity = !isPartner || (partnerPerms?.shareFlowIntensity == true)
    val showNotes = !isPartner || (partnerPerms?.shareSymptomsMoods == true)
    var expanded by remember { mutableStateOf(false) }
    val hasMultipleDays = group.dailyEntries.size > 1
    val isZeroFlow = group.maxIntensity == 0
    
    Card(
        modifier = Modifier.fillMaxWidth().then(
            if (hasMultipleDays) Modifier.clickable { expanded = !expanded }
            else if (!isPartner) Modifier.clickable { onEdit() }
            else Modifier
        ),
        shape = RoundedCornerShape(12.dp),
        colors = CardDefaults.cardColors(containerColor = Color.White),
        elevation = CardDefaults.cardElevation(defaultElevation = 2.dp)
    ) {
        Column {
            Row(
                modifier = Modifier.padding(16.dp),
                verticalAlignment = Alignment.CenterVertically
            ) {
                Box(
                    modifier = Modifier
                        .size(12.dp)
                        .clip(RoundedCornerShape(2.dp))
                        .then(
                            if (isZeroFlow) {
                                Modifier.border(1.5.dp, periodColor.copy(alpha = 0.7f), RoundedCornerShape(2.dp))
                            } else {
                                Modifier.background(periodColor)
                            }
                        )
                )
                
                Spacer(Modifier.width(16.dp))
                
                Column(modifier = Modifier.weight(1f)) {
                    val dateStr = if (!showIntensity && !isZeroFlow) {
                        "Period Logged (Dates Redacted)"
                    } else if (group.startDate == group.endDate) {
                        group.startDate.toHumanReadable()
                    } else {
                        "${group.startDate.toHumanReadable()} - ${group.endDate.toHumanReadable()}"
                    }
                    Text(dateStr, style = MaterialTheme.typography.titleSmall.copy(fontWeight = FontWeight.Bold))
                    
                    val intensityPart = if (showIntensity) {
                        if (isZeroFlow) {
                            "Flow: 0 · ${AppStrings.get("flow_0")}"
                        } else {
                            "Intensity: ${group.maxIntensity}"
                        }
                    } else ""
                    val painVal = group.maxPainLevel
                    val painPart = if (showNotes && painVal != null) " | Pain: ${if (painVal == 0) "0/10 (No pain)" else "$painVal/10"}" else ""
                    val sympPart = if (showNotes && group.symptoms.isNotEmpty()) "\nSymptoms: ${group.symptoms.joinToString(", ")}" else ""
                    val notesPart = if (showNotes && group.notes.isNotBlank()) "\n${group.notes}" else ""
                    val fullNotes = "$intensityPart$painPart$sympPart$notesPart".trimStart(' ', '|', '\n')
                    if (fullNotes.isNotBlank()) {
                        Text(fullNotes, style = MaterialTheme.typography.bodySmall, color = Color.Gray)
                    }
                    
                    if (hasMultipleDays) {
                        Spacer(Modifier.height(6.dp))
                        Text(
                            if (expanded) "▴ Hide Daily Breakdown (${group.dailyEntries.size} days)" else "▾ Daily Breakdown (${group.dailyEntries.size} days)",
                            style = MaterialTheme.typography.labelMedium,
                            color = periodColor,
                            fontWeight = FontWeight.SemiBold
                        )
                    }
                }
                
                if (!isPartner) {
                    Row(verticalAlignment = Alignment.CenterVertically) {
                        IconButton(onClick = onEdit) {
                            Icon(Icons.Default.Edit, contentDescription = "Edit period log", tint = periodColor, modifier = Modifier.size(20.dp))
                        }
                        IconButton(onClick = onDelete) {
                            Icon(Icons.Default.Delete, contentDescription = "Delete", tint = Color.LightGray, modifier = Modifier.size(20.dp))
                        }
                    }
                }
            }
            
            if (expanded && hasMultipleDays) {
                HorizontalDivider(color = Color.LightGray.copy(alpha = 0.4f), modifier = Modifier.padding(horizontal = 16.dp))
                Column(modifier = Modifier.fillMaxWidth().padding(horizontal = 16.dp, vertical = 8.dp)) {
                    group.dailyEntries.forEachIndexed { index, dayEntry ->
                        Row(
                            modifier = Modifier
                                .fillMaxWidth()
                                .padding(vertical = 6.dp)
                                .then(if (!isPartner) Modifier.clickable { onEditDay(dayEntry) } else Modifier),
                            verticalAlignment = Alignment.CenterVertically
                        ) {
                            val isDayZeroFlow = (dayEntry.intensity ?: 0) == 0
                            Box(
                                modifier = Modifier
                                    .size(6.dp)
                                    .clip(CircleShape)
                                    .then(
                                        if (isDayZeroFlow) {
                                            Modifier.border(1.dp, periodColor.copy(alpha = 0.7f), CircleShape)
                                        } else {
                                            Modifier.background(periodColor.copy(alpha = 0.7f))
                                        }
                                    )
                            )
                            Spacer(Modifier.width(12.dp))
                            Column(modifier = Modifier.weight(1f)) {
                                val dayDateText = if (!showIntensity && !isDayZeroFlow) "Day ${index + 1} (Date Redacted)" else kotlinx.datetime.LocalDate.parse(dayEntry.date).toHumanReadable()
                                Text("Day ${index + 1}: $dayDateText", style = MaterialTheme.typography.bodyMedium.copy(fontWeight = FontWeight.SemiBold))
                                
                                val intStr = if (showIntensity) {
                                    val intVal = dayEntry.intensity ?: 0
                                    if (intVal > 0) "Flow: $intVal" else "Flow: 0 · ${AppStrings.get("flow_0")}"
                                } else ""
                                val pVal = dayEntry.painLevel
                                val painStr = if (showNotes && pVal != null) "Pain: ${if (pVal == 0) "0/10 (No pain)" else "$pVal/10"}" else ""
                                val sympStr = if (showNotes && !dayEntry.symptoms.isNullOrBlank()) "Symptoms: ${dayEntry.symptoms?.replace(",", ", ")}" else ""
                                
                                val subDetails = listOf(intStr, painStr, sympStr).filter { it.isNotBlank() }.joinToString(" | ")
                                if (subDetails.isNotBlank()) {
                                    Text(subDetails, style = MaterialTheme.typography.bodySmall, color = Color.Gray)
                                } else {
                                    Text("No extra details logged", style = MaterialTheme.typography.bodySmall, color = Color.LightGray)
                                }
                            }
                            if (!isPartner) {
                                IconButton(onClick = { onEditDay(dayEntry) }, modifier = Modifier.size(48.dp)) {
                                    Icon(Icons.Default.Edit, contentDescription = "Edit Day ${index + 1}", tint = periodColor.copy(alpha = 0.8f), modifier = Modifier.size(16.dp))
                                }
                            }
                        }
                    }
                }
            }
        }
    }
}

@Composable
fun HistoryItem(entry: CycleEntry, isPartner: Boolean = false, partnerPerms: PartnerPermissions? = null, onEdit: () -> Unit, onDelete: () -> Unit) {
    val periodColor = LocalAppColors.current.primary
    val showIntensity = !isPartner || (partnerPerms?.shareFlowIntensity == true)
    val showNotes = !isPartner || (partnerPerms?.shareSymptomsMoods == true)
    val showSexual = !isPartner || (partnerPerms?.shareSexualActivity == true)
    val isZeroFlow = (entry.intensity ?: 0) == 0
    val isPeriodEntry = showIntensity && !isZeroFlow
    
    Card(
        modifier = Modifier.fillMaxWidth().then(
            if (!isPartner) Modifier.clickable { onEdit() } else Modifier
        ),
        shape = RoundedCornerShape(12.dp),
        colors = CardDefaults.cardColors(containerColor = Color.White),
        elevation = CardDefaults.cardElevation(defaultElevation = 2.dp)
    ) {
        Row(
            modifier = Modifier.padding(16.dp),
            verticalAlignment = Alignment.CenterVertically
        ) {
            Box(
                modifier = Modifier
                    .size(12.dp)
                    .clip(RoundedCornerShape(2.dp))
                    .then(
                        when {
                            isPeriodEntry -> Modifier.background(periodColor)
                            isZeroFlow -> Modifier.border(1.5.dp, periodColor.copy(alpha = 0.7f), RoundedCornerShape(2.dp))
                            else -> Modifier.background(Color.Gray)
                        }
                    )
            )
            
            Spacer(Modifier.width(16.dp))
            
            Column(modifier = Modifier.weight(1f)) {
                val dateText = kotlinx.datetime.LocalDate.parse(entry.date).toHumanReadable()
                Text(dateText, style = MaterialTheme.typography.titleSmall.copy(fontWeight = FontWeight.Bold))
                
                val notesStr = if (showNotes) (entry.notes ?: "") else ""
                val sympStr = if (showNotes && !entry.symptoms.isNullOrBlank()) "Symptoms: ${entry.symptoms?.replace(",", ", ")}" else ""
                val rel = if (showSexual) entry.sexualRelations else null
                val intensityPart = if (showIntensity) {
                    val intVal = entry.intensity ?: 0
                    if (intVal > 0) "Intensity: $intVal" else "Flow: 0 · ${AppStrings.get("flow_0")}"
                } else ""
                val painVal = entry.painLevel
                val painPart = if (showNotes && painVal != null) "Pain: ${if (painVal == 0) "0/10 (No pain)" else "$painVal/10"}" else ""
                val relPart = if (!rel.isNullOrBlank()) "Activity: ${rel.replaceFirstChar { it.uppercase() }}" else ""
                
                val topRow = listOf(intensityPart, painPart, relPart).filter { it.isNotBlank() }.joinToString(" | ")
                val midRow = if (sympStr.isNotBlank()) sympStr else ""
                val fullNotes = listOf(topRow, midRow, notesStr).filter { it.isNotBlank() }.joinToString("\n")
                
                Text(if (fullNotes.isBlank()) "No details" else fullNotes, style = MaterialTheme.typography.bodySmall, color = Color.Gray)
            }

            if (!isPartner) {
                Row(verticalAlignment = Alignment.CenterVertically) {
                    IconButton(onClick = onEdit) {
                        Icon(
                            Icons.Default.Edit, 
                            contentDescription = "Edit entry", 
                            tint = periodColor,
                            modifier = Modifier.size(20.dp)
                        )
                    }
                    IconButton(onClick = onDelete) {
                        Icon(
                            Icons.Default.Delete, 
                            contentDescription = "Delete entry", 
                            tint = Color.Gray.copy(alpha = 0.5f),
                            modifier = Modifier.size(20.dp)
                        )
                    }
                }
            }
        }
    }
}

